#!/usr/bin/env python3
"""Independent fixed-point numerical receipt for preregistered INSACERMO airfoil.
Produces a new Lean 4 arithmetic certificate from recomputed held-out residuals.
Does NOT modify or import original experimental Python or original C3 kernel.
This verifies quantized errors and their comparisons; not a physical law proof.
"""
import hashlib, io, json, math, urllib.request
from pathlib import Path
import numpy as np

URL=("https://raw.githubusercontent.com/rupakc/UCI-Data-Analysis/"
     "b2937bc0f36f570b5a6bb4049656f5239a1f334c/"
     "Airfoil%20Dataset/airfoil_self_noise.dat")
SOURCE_SHA256="10ee06e6cfb27dae6b44213d421d217012fb1f9b697592e73a4e4016b52d425f"
EXPECTED_BLOB="9f6fdafab6a323514c2a0407dea680fcb23d6795"
SEALED=Path("labs/airfoil_results_20261117/sealed_model_before_holdout.json")
REPORT=Path("labs/airfoil_results_20261117/audit.json")
SCALE=1000
FEATURES=("frequency","attack_angle","chord","wind_speed","displacement_thickness")

def blob_hash(payload):
    return hashlib.sha1(b"blob "+str(len(payload)).encode()+b"\0"+payload).hexdigest()

def design(x,means,stds):
    z=(x-means)/stds
    terms=[];names=[]
    def add(a,name):
        terms.append(np.clip(a,-100,100));names.append(name)
    for i,n in enumerate(FEATURES):add(z[:,i],n)
    for i,n in enumerate(FEATURES):
        v=np.log1p(np.maximum(x[:,i],0)) if i==1 else np.log(np.maximum(x[:,i],1e-12))
        add(v,n+":log")
    for i,n in enumerate(FEATURES):add(z[:,i]**2,n+":square")
    for i in range(5):
        for j in range(i+1,5):add(z[:,i]*z[:,j],FEATURES[i]+"*"+FEATURES[j])
    for i,n in enumerate(FEATURES):
        for k in (-.5,0,.5):add(np.maximum(0,z[:,i]-k),n+":hinge"+str(k))
    return np.column_stack(terms), names

def prediction(z,cols,beta):
    a=np.column_stack((np.ones(len(z)), z[:,cols])) if cols else np.ones((len(z),1))
    return a@np.asarray(beta)

def ridge(z,y,cols):
    a=np.column_stack((np.ones(len(z)),z[:,cols]))
    penalty=np.eye(len(cols)+1);penalty[0,0]=0
    return np.linalg.solve(a.T@a+penalty,a.T@y)

def main(folder):
    out=Path(folder);out.mkdir(parents=True,exist_ok=True)
    raw=urllib.request.urlopen(urllib.request.Request(URL,headers={"User-Agent":"INSACERMO-Lean-audit/1.0"}),timeout=80).read()
    assert hashlib.sha256(raw).hexdigest()==SOURCE_SHA256
    assert blob_hash(raw)==EXPECTED_BLOB
    xys=np.asarray([[float(t) for t in row.split()] for row in raw.decode().splitlines() if row.strip()],dtype=float)
    assert xys.shape==(1503,6)
    x=xys[:,:5]; y=xys[:,5]
    sealed=json.loads(SEALED.read_text()); prior=json.loads(REPORT.read_text())
    discovery=sealed["discovery_indices"]; challenge=sealed["challenge_indices"]
    holdout=sealed["holdout_row_ids"]; cols=sealed["selected_indices"]
    assert len(discovery)==733 and len(challenge)==40 and len(holdout)==281
    assert len(set(discovery+challenge+holdout))==len(discovery)+len(challenge)+len(holdout)
    assert all(abs(x[i,3]-31.7)<1e-9 for i in holdout)
    assert all(abs(x[i,3]-31.7)>1e-9 for i in discovery+challenge)
    z,names=design(x,np.asarray(sealed["mean"]),np.asarray(sealed["std"]))
    assert [names[i] for i in cols]==sealed["expressions"]
    ph=prediction(z[holdout],cols,sealed["coefficients"])
    tr=np.asarray(discovery+challenge)
    beta=ridge(z[tr],y[tr],list(range(5)))
    linear=prediction(z[holdout],list(range(5)),beta)
    rmse=lambda p:float(np.sqrt(np.mean((y[holdout]-p)**2)))
    current=rmse(ph); reference=rmse(linear)
    assert abs(current-prior["holdout_rmse_dB"])<1e-7,(current,prior["holdout_rmse_dB"])
    assert abs(reference-prior["linear_rmse_dB"])<1e-7,(reference,prior["linear_rmse_dB"])
    # Quantize signed residuals to nearest 0.001 dB and sum integer squares.
    # The error in each residual due to quantization is at most 0.0005 dB.
    residual_model=np.rint((y[holdout]-ph)*SCALE).astype(np.int64)
    residual_base=np.rint((y[holdout]-linear)*SCALE).astype(np.int64)
    s1=sum(int(v)*int(v) for v in residual_model)
    s0=sum(int(v)*int(v) for v in residual_base)
    n=len(holdout)
    assert 100*s1 < 81*s0, (s1,s0)
    assert s1 < 25*n*SCALE*SCALE
    # Margin >= quantization bound on RMSE: |RMSE(true)-RMSE(round)| <=0.0005dB.
    quant_rmse_1=math.sqrt(s1/n)/SCALE
    quant_rmse_0=math.sqrt(s0/n)/SCALE
    assert abs(quant_rmse_1-current)<=.0005+1e-10
    assert abs(quant_rmse_0-reference)<=.0005+1e-10
    # To avoid relying on rounded values for the true-valued claim:
    assert quant_rmse_1+.0005 < 5
    assert quant_rmse_1+.0005 < .9*(quant_rmse_0-.0005)
    lean=f"""-- Generated by independent Python numerical audit, not by INSACERMO C3.
-- Finite dataset, 281 residuals quantized to 0.001 dB.
-- Lean checks exact integer arithmetic of the bound, not numerical source fidelity.
namespace InsacermoAirfoilAudit
def count : Nat := {n}
def scale : Nat := {SCALE}
def modelSumSquares : Nat := {s1}
def linearSumSquares : Nat := {s0}
theorem heldout_count : count = 281 := by decide
theorem rmse_below_five_quantized :
    modelSumSquares < 25 * count * scale * scale := by decide
theorem rmse_ten_percent_better_quantized :
    100 * modelSumSquares < 81 * linearSumSquares := by decide
end InsacermoAirfoilAudit
"""
    (out/"AirfoilArithmeticCertificate.lean").write_text(lean)
    receipt=dict(rows=n,quantization_dB=.001,sse_selected_millidB_squared=s1,
        sse_linear_millidB_squared=s0,model_rmse_recomputed=current,
        linear_rmse_recomputed=reference,quantized_model_rmse=quant_rmse_1,
        quantized_linear_rmse=quant_rmse_0,
        integer_ten_percent_test=100*s1<81*s0,
        integer_five_dB_test=s1<25*n*SCALE*SCALE,
        conservative_rounding_acceptance=True,
        holdout_indices_sha256=hashlib.sha256(json.dumps(holdout,separators=(",",":")).encode()).hexdigest(),
        source_sha256=SOURCE_SHA256,
        limits=["Lean certifies finite integer arithmetic only; Python reconstructs observations and floating-point predictions.",
          "No formal IEEE floating-point verification or new physical law proof.",
          "The original INSACERMO C3 engine and historical Lean corpus are unchanged."])
    (out/"numerical_receipt.json").write_text(json.dumps(receipt,indent=2)+"\n")
    print("AIRFOIL_INTEGER_PROOF_INPUT",s1,s0,"N",n)
    print("AIRFOIL_FLOAT_RECOMPUTED",current,reference)
    print("AIRFOIL_CONSERVATIVE_QUANTIZATION_PASS",flush=True)

if __name__=="__main__":
    import sys
    main(sys.argv[1] if len(sys.argv)>1 else "/tmp/insacermo_airfoil_lean")
